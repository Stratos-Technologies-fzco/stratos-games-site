// How well current conditions suit an organism (0.2 .. 1).
export function envFit(org, env) {
  const axis = (v, [lo, hi], width) => (v >= lo && v <= hi ? 1 : Math.exp(-(v < lo ? lo - v : v - hi) / width));
  const f = axis(env.hum, org.env.hum, 12) * axis(env.temp, org.env.temp, 5);
  return Math.max(0.2, f);
}
